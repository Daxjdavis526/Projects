/* TS-3G's own interlocks. The generic ones (fire circuit, cell, DAQ) are
   in control/interlocks.js. */

import { psi } from '../../lib/units.js';
import { S, ALL_BLOCK } from '../../control/interlocks.js';

const TANK_REGS = ['PR-410', 'PR-420'];
const VENT_OF = { 'PR-410': 'VV-413', 'PR-420': 'VV-423' };
const plan = c => ({ startP: psi(220), mainOpen: 0.45, ggOpen: 0.75, spinEnd: 1.1, ignLead: 0.5, ignOff: 2.0, thr: 1, ...(c.plan || {}) });

export function interlocks(def) {
  const R = def.ratings;
  const maxSystem = c => Math.max(...['PT-302', 'PT-410', 'PT-420', 'PT-336', 'PT-333', 'PT-414', 'PT-424', 'PT-630', 'PT-501'].map(id => c.meas(id)).filter(Number.isFinite), -Infinity);
  return [
    { id: 'FIRE-DRY', on: ['arm', 'fire'], sev: ALL_BLOCK, safety: true,
      test: c => c.loaded !== 'water' && c.loaded !== 'propellants',
      msg: 'The run tanks are empty.',
      why: 'A pump with no liquid has no load. Spin the turbine and the shaft runs away to overspeed.' },
    { id: 'FIRE-COLD-PROP', on: ['arm', 'fire'], sev: ALL_BLOCK, safety: true,
      test: c => c.loaded === 'propellants' && plan(c).mode === 'cold',
      msg: 'A cold-flow plan with propellants in the tanks.',
      why: 'Pumping OX-1 and FU-1 through the injector with the igniters off fills the chamber and the cell with unburned propellant. Drain and load water for a cold flow.' },
    { id: 'FIRE-HOT-WATER', on: ['arm', 'fire'], sev: ALL_BLOCK,
      test: c => c.loaded === 'water' && plan(c).mode === 'hot',
      msg: 'A hot-fire plan with water in the tanks.',
      why: 'Nothing would light. The start checks would abort it at the first one.' },
    { id: 'FIRE-NPSH', on: ['arm', 'fire'], sev: S('block', 'warn', 'allow'),
      test: c => c.sp['PR-410'] < R.NPSH_MIN_TANK || c.sp['PR-420'] < R.NPSH_MIN_TANK,
      msg: `Tank setpoint below ${Math.round(R.NPSH_MIN_TANK / 6894.757)} psig.`,
      why: 'The pumps would run close to cavitation at mainstage. On an engine a cavitating pump unloads the turbine: the shaft speeds up while the chamber starves.' },
    { id: 'FIRE-START', on: ['arm', 'fire'], sev: ALL_BLOCK,
      test: c => { const p = plan(c); return !(p.startP >= psi(120) && p.startP <= R.START_MAX); },
      msg: 'Start gas pressure outside 120–400 psig.',
      why: 'Below 120 psig the start gas cannot bring the pumps up to the pressure the gas generator needs; above 400 it overspeeds the turbine before the main valves load it.' },
    { id: 'FIRE-TIMING', on: ['arm', 'fire'], sev: S('block', 'block', 'warn'), safety: true,
      test: c => { const p = plan(c); return p.mode === 'hot' && !(p.mainOpen > 0.15 && p.ggOpen > p.mainOpen && p.spinEnd > p.ggOpen + 0.15 && p.spinEnd < 3 && p.ignLead > 0 && p.ignOff > p.ggOpen + 0.5); },
      msg: 'Start timing out of order: main valves, then the gas generator, then the start gas off — with the igniters sparking throughout.',
      why: 'The gas generator must light on pump pressure that the main valves have already loaded, and the start gas must still be on when it does — or the engine never bootstraps.' },
    { id: 'FIRE-THROTTLE', on: ['arm', 'fire'], sev: S('block', 'block', 'warn'),
      test: c => { const p = plan(c); const xs = p.thrSteps?.length ? p.thrSteps : [p.thrOx ?? p.thr, p.thrFu ?? p.thr]; return xs.some(x => !(x >= R.THR_MIN && x <= 1)); },
      msg: 'A GG throttle setting below 60 % (or above 100 %).',
      why: 'Below 60 % the gas generator cannot hold the pumps at a speed where the injectors stay stiff: chug.' },
    { id: 'FIRE-CASE', on: ['arm', 'fire'], sev: S('block', 'warn', 'allow'),
      test: c => c.loaded === 'propellants' && c.meas('TC-503') > R.CASE_REFIRE,
      msg: 'Chamber case still above 60 °C from the last burn.',
      why: 'The ablative soaks back long after shutdown. Fire it warm and the case redline comes early.' },
    { id: 'FIRE-PURGE', on: ['arm', 'fire'], sev: S('block', 'block', 'warn'), safety: true,
      test: c => !(c.meas('PT-630') >= R.PURGE_MIN),
      msg: 'Purge pressure below 100 psig.',
      why: 'No purge, no way to clear the injector manifolds and the turbine manifold before and after the run.' },
    { id: 'FIRE-DRIVEVENT', on: ['arm', 'fire'], sev: S('block', 'block', 'warn'),
      test: c => c.cmd('VV-338') === 1,
      msg: 'The start gas line vent VV-338 is open.',
      why: 'Open, it bleeds the start gas to the cell.' },
    { id: 'FIRE-SPARK', on: ['arm'], sev: S('block', 'warn', 'allow'),
      test: c => c.loaded === 'propellants' && !c.sparkChecked,
      msg: 'The igniters have not been spark-checked today.',
      why: 'A main chamber that does not light fills with propellant; a gas generator that does not light sends it through the turbine.' },
    { id: 'ARM-SUPPLY', on: ['arm'], sev: S('block', 'warn', 'allow'),
      test: c => !(c.meas('PT-301') >= R.SUPPLY_MIN),
      msg: 'Bottle bank below 1200 psig.',
      why: 'The start gas, the purges and both tanks all come from the bank.' },
    { id: 'ENTER-SPIN', on: ['enterCell'], sev: ALL_BLOCK, safety: true,
      test: c => c.meas('SPD') > 300,
      msg: 'The turbopump is turning.',
      why: 'Nobody enters the cell until it has stopped.' },
    { id: 'ENTER-PRESS', on: ['enterCell'], sev: S('block', 'warn', 'allow'), safety: true,
      test: c => maxSystem(c) > R.PERSONNEL_MAX,
      msg: 'Tanks or lines are pressurised above the personnel limit (50 psig).',
      why: 'Vent first.' },
    { id: 'REG-PERSONNEL', on: ['regSet'], sev: S('block', 'warn', 'allow'), safety: true,
      test: (c, x) => x.value > R.PERSONNEL_MAX && c.facility.area !== 'SECURED',
      msg: 'Setpoint above the 50 psig personnel limit with the cell open.',
      why: 'Clear and secure the cell before pressurising beyond the personnel limit.' },
    { id: 'REG-MEOP', on: ['regSet'], sev: S('warn', 'warn', 'warn'),
      test: (c, x) => TANK_REGS.includes(x.id) && x.value > R.TANK_MEOP && x.value <= R.REG_MAX_CMD,
      msg: 'Tank setpoint above MEOP (120 psig).', why: 'You are eating into the margin to the tank reliefs (150 psig).' },
    { id: 'REG-MAX', on: ['regSet'], sev: ALL_BLOCK,
      test: (c, x) => x.value > (x.id === 'PR-330' ? R.START_MAX : x.id === 'PR-630' ? R.PURGE_MAX : R.REG_MAX_CMD),
      msg: 'Setpoint above the EPC software limit.', why: 'The EPC will not command a dome pressure this close to the relief setting.' },
    { id: 'REG-START', on: ['regSet'], sev: S('block', 'warn', 'warn'),
      test: (c, x) => x.id === 'PR-330' && x.value > 0,
      msg: 'The sequencer sets the start gas.',
      why: 'PR-330 is brought up by the sequencer at T-3 and down after the start. Set by hand, start gas sits behind TSV-332 with nothing to account for it.' },
    { id: 'REG-VENTING', on: ['regSet'], sev: S('warn', 'warn', 'allow'),
      test: (c, x) => VENT_OF[x.id] && x.value > 0 && c.cmd(VENT_OF[x.id]) === 1,
      msg: 'That tank\'s vent is open: the regulator will flow straight out of it.', why: 'Close the tank vent before pressurising the tank.' },
    { id: 'IV-VENTING', on: ['valve'], sev: S('warn', 'warn', 'allow'),
      test: (c, x) => x.id === 'IV-301' && x.open && c.cmd('VV-301') === 1,
      msg: 'VV-301 is open: gas will flow straight to the vent.', why: 'Close the header vent first.' },
    { id: 'MAIN-MANUAL', on: ['valve'], sev: S('block', 'block', 'warn'),
      test: (c, x) => def.sequencedValves.includes(x.id),
      msg: 'The start valve, the main valves, the gas generator valves and throttles are operated by the sequencer.',
      why: 'An engine started by hand is a start with no recording, no start checks and no abort coverage.' },
  ];
}
