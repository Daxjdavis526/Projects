// Regenerates content/loads.js — the table that tells the catalog which
// lessons are built — from the lesson files on disk. A lesson file is
// content/<course>/<MODULE>.<n>.js and holds the lesson <course>.<MODULE>.<n>;
// content/<course>/boss.js is that course's authored boss battle. Files whose
// names start with "_" are shared helpers and are skipped.
//   node atlas/tools/register.mjs          rewrite content/loads.js
//   node atlas/tools/register.mjs --check  exit 1 if it is out of date

import { readdirSync, readFileSync, writeFileSync, renameSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const CONTENT = join(dirname(fileURLToPath(import.meta.url)), '..', 'content');
const LESSON_FILE = /^[A-Za-z0-9-]+\.[0-9a-z]+\.js$/;

export function scan() {
  const lessons = [], bosses = [];
  for (const course of readdirSync(CONTENT).sort()) {
    const dir = join(CONTENT, course);
    if (course.startsWith('_') || !statSync(dir).isDirectory()) continue;
    for (const f of readdirSync(dir).sort(byLesson)) {
      if (f.startsWith('_')) continue;
      if (f === 'boss.js') bosses.push(course);
      else if (LESSON_FILE.test(f)) lessons.push({ id: `${course}.${f.slice(0, -3)}`, path: `./${course}/${f}` });
    }
  }
  return { lessons, bosses };
}

// C2-2.10 after C2-2.9: compare the dotted parts numerically where they are numbers
function byLesson(a, b) {
  const pa = a.split('.'), pb = b.split('.');
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const x = pa[i] ?? '', y = pb[i] ?? '';
    if (x === y) continue;
    const nx = /^\d+$/.test(x), ny = /^\d+$/.test(y);
    if (nx && ny) return +x - +y;
    return x < y ? -1 : 1;
  }
  return 0;
}

export function render({ lessons, bosses }) {
  return [
    '// Generated by `node atlas/tools/register.mjs` from the lesson files on disk.',
    '// Do not edit by hand: add or remove a lesson file and run the tool again.',
    '',
    'export const LESSONS = {',
    ...lessons.map((l) => `  '${l.id}': () => import('${l.path}'),`),
    '};',
    '',
    'export const BOSSES = {',
    ...bosses.map((c) => `  '${c}': () => import('./${c}/boss.js'),`),
    '};',
    '',
  ].join('\n');
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const file = join(CONTENT, 'loads.js');
  const want = render(scan());
  let have = '';
  try { have = readFileSync(file, 'utf8'); } catch { /* first run */ }
  if (process.argv.includes('--check')) {
    if (have !== want) { console.log('content/loads.js is out of date — run: node atlas/tools/register.mjs'); process.exit(1); }
    console.log('content/loads.js is up to date');
  } else if (have !== want) {
    // write-then-rename, so two authors registering at once never leave a torn file
    const tmp = `${file}.${process.pid}.tmp`;
    writeFileSync(tmp, want);
    renameSync(tmp, file);
    const s = scan();
    console.log(`content/loads.js: ${s.lessons.length} lessons, ${s.bosses.length} bosses`);
  } else console.log(`content/loads.js already up to date (${scan().lessons.length} lessons — a new lesson may have been registered by another author's run)`);
}
