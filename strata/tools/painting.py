#!/usr/bin/env python3
"""Turn a picture into STRATA's block painting (src/Gen/Landmarks/PaintingData.cs).

The picture is scaled to WIDTH x HEIGHT blocks and reduced to COLOURS flat
colours. Each colour becomes one solid-colour Pigment block (src/Data/Blocks.cs)
and each pixel one block of the painting the Gallery landmark stands in the
showcase world (src/Gen/Landmarks/Gallery.cs).

    python3 strata/tools/painting.py <picture> [--preview out.png]

Needs Pillow. The picture itself is not kept: only the palette and the block
grid it becomes, written into PaintingData.cs.
"""
import argparse
import base64
import os
import zlib

from PIL import Image

WIDTH, HEIGHT, COLOURS = 360, 240, 64
OUT = os.path.join(os.path.dirname(__file__), '..', 'src', 'Gen', 'Landmarks', 'PaintingData.cs')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('picture')
    ap.add_argument('--preview', help='also write the block grid, scaled up, to this PNG')
    a = ap.parse_args()

    img = Image.open(a.picture).convert('RGB')
    # Fill the painting's 3:2 frame: crop the picture's longer side to fit, then scale.
    want = WIDTH / HEIGHT
    w, h = img.size
    if w / h > want:
        cw = round(h * want)
        img = img.crop(((w - cw) // 2, 0, (w - cw) // 2 + cw, h))
    else:
        ch = round(w / want)
        img = img.crop((0, (h - ch) // 2, w, (h - ch) // 2 + ch))
    img = img.resize((WIDTH, HEIGHT), Image.Resampling.LANCZOS)
    q = img.quantize(colors=COLOURS, method=Image.Quantize.MEDIANCUT, kmeans=8, dither=Image.Dither.NONE)

    raw = q.getpalette()[:COLOURS * 3]
    pal = [tuple(raw[i * 3:i * 3 + 3]) for i in range(COLOURS)]
    # Darkest first, so the pigment blocks list in a sensible order.
    order = sorted(range(COLOURS), key=lambda i: 0.2126 * pal[i][0] + 0.7152 * pal[i][1] + 0.0722 * pal[i][2])
    remap = {old: new for new, old in enumerate(order)}
    pal = [pal[i] for i in order]
    flat = q.get_flattened_data() if hasattr(q, 'get_flattened_data') else q.getdata()
    cells = bytes(remap[v] for v in flat)

    data = base64.b64encode(zlib.compress(cells, 9)).decode()
    lines = [data[i:i + 116] for i in range(0, len(data), 116)]
    hexes = [f'0x{r:02x}{g:02x}{b:02x}' for r, g, b in pal]
    with open(OUT, 'w', newline='\n') as f:
        f.write('// Generated by strata/tools/painting.py: do not edit by hand.\n')
        f.write('namespace Strata;\n\n')
        f.write('/// <summary>The Gallery painting: its size, the colours of the Pigment blocks, and a palette index per\n')
        f.write('/// block, row by row from the top-left (zlib-deflated, then base64).</summary>\n')
        f.write('public static class PaintingData\n{\n')
        f.write(f'    public const int Width = {WIDTH}, Height = {HEIGHT};\n\n')
        f.write('    public static readonly uint[] Palette =\n    {\n')
        for i in range(0, COLOURS, 8):
            f.write('        ' + ', '.join(hexes[i:i + 8]) + ',\n')
        f.write('    };\n\n')
        f.write('    public const string Cells =\n')
        for i, ln in enumerate(lines):
            f.write(f'        "{ln}"' + (' +\n' if i < len(lines) - 1 else ';\n'))
        f.write('}\n')
    print(f'wrote {os.path.normpath(OUT)}: {WIDTH} x {HEIGHT} blocks, {COLOURS} colours, {len(data)} characters of data')

    if a.preview:
        out = Image.new('RGB', (WIDTH, HEIGHT))
        out.putdata([pal[c] for c in cells])
        out.resize((WIDTH * 4, HEIGHT * 4), Image.Resampling.NEAREST).save(a.preview)


if __name__ == '__main__':
    main()
