#!/usr/bin/env python3
"""Turns a photo into the data the world generator builds the launch complex's mosaic from.

    python3 strata/tools/portrait.py PHOTO.png

Crops the photo to the mosaic's 9:14 shape (from TOP down, the full width),
scales it to one pixel per block (Portrait.W x Portrait.H), and writes the
pixels as base64 RGB into src/Gen/Landmarks/PortraitData.cs. The game picks a
pigment block for each pixel itself (src/Gen/Landmarks/Portrait.cs), so the
palette lives in one place only. Needs Pillow.
"""
import base64
import sys
from pathlib import Path

from PIL import Image

W, H = 90, 140      # must match Portrait.W and Portrait.H
TOP = 300           # pixels to drop from the top of the screenshot (the app's name bar)

def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = Image.open(sys.argv[1]).convert('RGB')
    w = src.width
    h = round(w * H / W)
    if TOP + h > src.height:
        sys.exit(f'photo too short for a {W}:{H} crop from y={TOP}')
    img = src.crop((0, TOP, w, TOP + h)).resize((W, H), Image.LANCZOS)
    data = base64.b64encode(img.tobytes()).decode('ascii')
    lines = [data[i:i + 116] for i in range(0, len(data), 116)]
    body = '\n'.join(f'        "{line}" +' for line in lines)
    out = Path(__file__).resolve().parent.parent / 'src' / 'Gen' / 'Landmarks' / 'PortraitData.cs'
    out.write_text(f'''// Generated by tools/portrait.py from the supplied photo: do not edit by hand.
namespace Strata;

/// <summary>The mosaic's picture: {W} × {H} pixels, RGB, row by row from the top, base64.</summary>
public static class PortraitData
{{
    public const int W = {W}, H = {H};

    public const string Rgb =
{body}
        "";
}}
''')
    print(f'wrote {out} ({len(data)} chars)')

if __name__ == '__main__':
    main()
